"""Pydantic is the single wire-schema source; --check prevents stale TS builds."""
import json
import sys
from pathlib import Path

root = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(root / "services/companion/src"))
from cypher.contracts import SettingsV1, VideoContext, Transcript, JobRequest, JobSnapshot, ExportDocument
from cypher.languages import LANGUAGE_OPTIONS

schemas = {model.__name__: model.model_json_schema(mode="serialization") for model in (
    SettingsV1, VideoContext, Transcript, JobRequest, JobSnapshot, ExportDocument)}
target = root / "packages/contracts/src/generated.ts"
content = "// Generated by tools/export-contracts.py. Do not edit.\nexport const schemas = " + json.dumps(schemas, ensure_ascii=False, indent=2) + " as const;\n"
content += "export const defaultSettings = " + json.dumps(SettingsV1().model_dump(), indent=2) + " as const;\n"
content += "export const languageOptions = " + json.dumps(LANGUAGE_OPTIONS,ensure_ascii=False,indent=2) + " as const;\n"
if "--check" in sys.argv:
    if not target.exists() or target.read_text(encoding="utf-8") != content:
        raise SystemExit("Generated wire schemas are stale")
else:
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(content, encoding="utf-8", newline="\n")
